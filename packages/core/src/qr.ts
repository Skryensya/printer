function u8(bytes: number[]): Uint8Array {
  return new Uint8Array(bytes);
}

export function buildQR(text: string, size = 8, errorLevel: "L"|"M"|"Q"|"H" = "M"): Uint8Array[] {
  const errByte = { L: 48, M: 49, Q: 50, H: 51 }[errorLevel];
  const data = new TextEncoder().encode(text);
  const dataLen = data.length + 3;
  return [
    u8([0x1D, 0x28, 0x6B, 0x04, 0x00, 0x31, 0x41, 0x32, 0x00]),
    u8([0x1D, 0x28, 0x6B, 0x03, 0x00, 0x31, 0x43, size]),
    u8([0x1D, 0x28, 0x6B, 0x03, 0x00, 0x31, 0x45, errByte]),
    u8([0x1D, 0x28, 0x6B, dataLen & 0xFF, (dataLen >> 8) & 0xFF, 0x31, 0x50, 0x30, ...data]),
    u8([0x1D, 0x28, 0x6B, 0x03, 0x00, 0x31, 0x51, 0x30]),
  ];
}
